package edu.integration.b.web.dto;

public class CrossChoiceSyncRequest {
  private String action;
  private String sno;
  private String cno;
  private String destSystem;
  private String cnm;
  private String ctm;
  private String cpt;
  private String tec;
  private String pla;
  private String share;
  private String grd;

  public CrossChoiceSyncRequest() {}

  public String getAction() {
    return action;
  }

  public void setAction(String action) {
    this.action = action;
  }

  public String getSno() {
    return sno;
  }

  public void setSno(String sno) {
    this.sno = sno;
  }

  public String getCno() {
    return cno;
  }

  public void setCno(String cno) {
    this.cno = cno;
  }

  public String getDestSystem() {
    return destSystem;
  }

  public void setDestSystem(String destSystem) {
    this.destSystem = destSystem;
  }

  public String getCnm() {
    return cnm;
  }

  public void setCnm(String cnm) {
    this.cnm = cnm;
  }

  public String getCtm() {
    return ctm;
  }

  public void setCtm(String ctm) {
    this.ctm = ctm;
  }

  public String getCpt() {
    return cpt;
  }

  public void setCpt(String cpt) {
    this.cpt = cpt;
  }

  public String getTec() {
    return tec;
  }

  public void setTec(String tec) {
    this.tec = tec;
  }

  public String getPla() {
    return pla;
  }

  public void setPla(String pla) {
    this.pla = pla;
  }

  public String getShare() {
    return share;
  }

  public void setShare(String share) {
    this.share = share;
  }

  public String getGrd() {
    return grd;
  }

  public void setGrd(String grd) {
    this.grd = grd;
  }
}
